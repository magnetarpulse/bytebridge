import { setupWorker } from 'msw/browser';
import { handlers } from './handlers';

/**
 * Mock Service Worker instance.
 * 
 * @remarks
 * This worker intercepts HTTP requests in the browser and returns mock responses
 * based on the handlers defined in './handlers'. It enables development without
 * connecting to actual API endpoints.
 * 
 * @see {@link https://mswjs.io/docs/ MSW Documentation}
 */
export const worker = setupWorker(...handlers);

/**
 * Starts the Mock Service Worker for API request interception.
 * 
 * @remarks
 * This function should only be called in development mode when mock API is enabled.
 * It configures MSW to:
 * - Intercept matching API requests and return mock responses
 * - Ignore static assets (images, fonts, stylesheets, etc.)
 * - Ignore client-side routing requests
 * - Warn about unhandled API requests that don't have mock handlers
 * 
 * The worker uses a service worker file (`/mockServiceWorker.js`) that must be
 * present in the public directory. This file is generated by MSW during setup.
 * 
 * @returns Promise that resolves when the worker is started, or immediately if mocking is disabled
 * 
 * @example
 * ```typescript
 * // In main.tsx or app entry point
 * await startMockWorker();
 * // Now all matching API requests will be intercepted
 * ```
 */
export async function startMockWorker(): Promise<void> {
  if (import.meta.env.DEV && import.meta.env.VITE_USE_MOCK_API !== 'false') {
    await worker.start({
      serviceWorker: {
        /**
         * Path to the service worker file.
         * Must match the location of mockServiceWorker.js in the public directory.
         */
        url: '/mockServiceWorker.js',
      },
      
      /**
       * Handler for requests that don't match any defined mock handlers.
       * 
       * @param request - The unhandled request object
       * @param print - MSW's print utilities for logging
       */
      onUnhandledRequest(request, print) {
        const url = new URL(request.url);
        
        /**
         * Static asset file extensions that should be ignored.
         * These are typically served by Vite's dev server, not API endpoints.
         */
        const staticExtensions = [
          '.png', '.jpg', '.jpeg', '.gif', '.svg', '.ico',
          '.woff', '.woff2', '.ttf', '.eot',
          '.css', '.js', '.map'
        ];
        
        /** Check if the request is for a static asset */
        const isStaticAsset = staticExtensions.some(ext => url.pathname.endsWith(ext));
        
        /**
         * Check if the request is a client-side route.
         * Client routes have no file extension and don't target API endpoints.
         */
        const isClientRoute = 
          !url.pathname.includes('.') && 
          !url.pathname.includes('/api') && 
          !url.pathname.includes('/users');
        
        // Silently bypass static assets and client-side routes
        if (isStaticAsset || isClientRoute) {
          return;
        }
        
        // Warn about unhandled API endpoint requests
        print.warning();
      },
    });
    return;
  }
  
  // Return resolved promise if mocking is disabled
  return Promise.resolve();
}