@login_required
def datastore_detail(request, datastore_id):
    """View for displaying details of a DataStore with synchronization capability."""
    datastore = get_object_or_404(DataStore, id=datastore_id, owner=request.user)
    
    # Get related buckets
    buckets = datastore.buckets.all()
    
    # Get storage statistics
    bucket_count = buckets.count()
    object_count = 0
    total_size = 0
    
    for bucket in buckets:
        # Add bucket-specific data
        bucket_objects = bucket.stored_objects.all()
        bucket.object_count = bucket_objects.count()
        object_count += bucket.object_count
        
        # Calculate size
        bucket_size = bucket_objects.aggregate(Sum('size')).get('size__sum') or 0
        total_size += bucket_size
    
    return render(request, 'integrations/datastore_detail.html', {
        'datastore': datastore,
        'buckets': buckets,
        'bucket_count': bucket_count,
        'object_count': object_count,
        'total_size': total_size
    })

# API endpoint for ByteBridge registration
@csrf_exempt
@login_required
@require_http_methods(["POST"])
def api_register_instance(request):
    try:
        data = json.loads(request.body)
        instance_id = data.get('instance_id')
        id_token = data.get('id_token')
        verifier_token = data.get('verifier_token')
        register_token = data.get('register_token')
        
        # Validate inputs
        if not all([instance_id, id_token, verifier_token, register_token]):
            return JsonResponse({
                'status': 'error', 
                'message': 'Missing required fields'
            }, status=400)
        
        # Get the instance
        instance = get_object_or_404(ByteBridgeInstance, id=instance_id, owner=request.user)
        
        # Create client and register - this handles 2FA internally in register.py
        client = NeuroControllerClient()
        success, _, error_message = client.register_bytebridge(
            instance, id_token, verifier_token, register_token
        )
        
        if success:
            # Update instance as registered
            instance.is_registered = True
            instance.save()
            
            return JsonResponse({
                'status': 'success',
                'message': 'ByteBridge instance registered successfully'
            })
        else:
            return JsonResponse({
                'status': 'error',
                'message': error_message or 'Registration failed'
            }, status=400)
    
    except Exception as e:
        return JsonResponse({
            'status': 'error',
            'message': f'An error occurred: {str(e)}'
        }, status=500)

