# ByteBridge Instance Registration
@login_required
def register_instance(request):
    # Get instances
    instances = ByteBridgeInstance.objects.filter(owner=request.user).order_by('-created_at')
    
    # Get or create an instance for the current server
    hostname = request.get_host()
    api_endpoint = f"{settings.API_PROTOCOL}://{settings.API_HOST}:{settings.API_PORT}/api/v1"
    
    # Need to generate a unique api_token if creating a new instance
    import secrets
    random_token = secrets.token_hex(16)
    
    # Create or get the instance using only fields that exist in the model
    current_instance, _ = ByteBridgeInstance.objects.get_or_create(
        name=f"Local instance ({hostname})",
        owner=request.user,
        defaults={
            'is_active': True,
            'api_token': f"token_{random_token}"  # Generate a unique API token
            # Don't set instance_id - it's automatically generated by pre_save signal
        }
    )
    
    context = {
        'active_tab': 'register_instance',
        'instances': instances,
        'current_instance': current_instance,
        'api_endpoint': api_endpoint,  # Pass this separately to the template
    }
    return render(request, 'integrations/register_instance.html', context)

