# API endpoint for creating a DataStore    
@csrf_exempt
@login_required
@require_http_methods(["POST"])
def api_create_datastore(request):
    try:
        data = json.loads(request.body)
        name = data.get('name')
        instance_id = data.get('instance_id')
        permission_type = data.get('permission_type')
        description = data.get('description', '')
        
        # Validate inputs
        if not all([name, instance_id, permission_type]):
            return JsonResponse({
                'status': 'error', 
                'message': 'Missing required fields'
            }, status=400)
        
        # Validate permission type
        valid_permissions = [choice[0] for choice in DataStore.PERMISSION_CHOICES]
        if permission_type not in valid_permissions:
            return JsonResponse({
                'status': 'error',
                'message': f'Invalid permission type. Must be one of: {", ".join(valid_permissions)}'
            }, status=400)
        
        # Get the instance
        instance = get_object_or_404(ByteBridgeInstance, id=instance_id, owner=request.user)
        
        # Create the datastore
        datastore = DataStore.objects.create(
            name=name,
            instance=instance,
            owner=request.user,
            permission_type=permission_type,
            description=description,
            is_active=True
        )
        
        return JsonResponse({
            'status': 'success',
            'message': 'DataStore created successfully',
            'datastore_id': datastore.id,
            'datastore_name': datastore.name
        })
        
    except Exception as e:
        return JsonResponse({
            'status': 'error',
            'message': f'An error occurred: {str(e)}'
        }, status=500)

@csrf_exempt  
@login_required
@require_http_methods(["POST"])
def api_sync_datastore(request):
    """API endpoint to synchronize a datastore's contents with NeuroController"""
    print("Got sync request")
    print(f"Request body: {request.body}")
    try:
        data = json.loads(request.body)
        datastore_id = data.get('datastore_id')

        print("Request data:", data)
        print("Datastore ID:", datastore_id)
        
        # Validate inputs
        if not datastore_id:
            print("Missing datastore_id")
            return JsonResponse({
                'status': 'error', 
                'message': 'Missing datastore_id'
            }, status=400)
        
        
        # Get the datastore
        datastore = get_object_or_404(DataStore, id=datastore_id, owner=request.user)
        
        # Make sure the instance is registered
        if not datastore.instance.is_registered:
            print("Instance is not registered")
            return JsonResponse({
                'status': 'error',
                'message': 'ByteBridge instance is not registered with NeuroController'
            }, status=400)
        
        # Create client and synchronize
        client = NeuroControllerClient()
        success, stats, error_message = client.sync_datastore_contents(datastore)
        print("Sync result:", success, stats, error_message)
        
        if success:
            print("Sync successful")
            return JsonResponse({
                'status': 'success',
                'message': 'DataStore synchronized successfully',
                'stats': stats
            })
        else:
            print("Sync failed")
            return JsonResponse({
                'status': 'error',
                'message': error_message or 'Synchronization failed'
            }, status=400)
    
    except Exception as e:
        print("Error during sync:", str(e))
        return JsonResponse({
            'status': 'error',
            'message': f'An error occurred: {str(e)}'
        }, status=500)
